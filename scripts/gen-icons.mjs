// Generates resources/icon.png (256x256 app icon) and src/main/trayIcon.ts
// (embedded 16x16 tray icon) with a dependency-free PNG encoder.
import { deflateSync } from 'node:zlib'
import { mkdirSync, writeFileSync } from 'node:fs'

const CRC_TABLE = (() => {
  const table = new Int32Array(256)
  for (let n = 0; n < 256; n++) {
    let c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    table[n] = c
  }
  return table
})()

function crc32(buf) {
  let c = 0xffffffff
  for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}

function chunk(type, data) {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body))
  return Buffer.concat([len, body, crc])
}

function encodePng(width, height, rgba) {
  const sig = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(width, 0)
  ihdr.writeUInt32BE(height, 4)
  ihdr[8] = 8 // bit depth
  ihdr[9] = 6 // RGBA
  const raw = Buffer.alloc(height * (width * 4 + 1))
  for (let y = 0; y < height; y++) {
    raw[y * (width * 4 + 1)] = 0 // filter: none
    rgba.copy(raw, y * (width * 4 + 1) + 1, y * width * 4, (y + 1) * width * 4)
  }
  return Buffer.concat([
    sig,
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0))
  ])
}

// --- drawing helpers ---

function makeCanvas(size) {
  return { size, data: Buffer.alloc(size * size * 4) }
}

function setPx(canvas, x, y, [r, g, b, a]) {
  if (x < 0 || y < 0 || x >= canvas.size || y >= canvas.size) return
  const i = (y * canvas.size + x) * 4
  canvas.data[i] = r
  canvas.data[i + 1] = g
  canvas.data[i + 2] = b
  canvas.data[i + 3] = a
}

function inRoundedRect(x, y, x0, y0, x1, y1, radius) {
  if (x < x0 || x > x1 || y < y0 || y > y1) return false
  const cx = Math.max(x0 + radius, Math.min(x, x1 - radius))
  const cy = Math.max(y0 + radius, Math.min(y, y1 - radius))
  return (x - cx) ** 2 + (y - cy) ** 2 <= radius ** 2 || (x === cx && y === cy)
}

function drawIcon(size) {
  const canvas = makeCanvas(size)
  const s = size / 256
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      // Rounded-square background with a subtle vertical gradient.
      if (!inRoundedRect(x, y, 8 * s, 8 * s, size - 8 * s, size - 8 * s, 48 * s)) continue
      const t = y / size
      setPx(canvas, x, y, [
        Math.round(64 + 30 * t),
        Math.round(84 + 40 * t),
        Math.round(196 + 20 * t),
        255
      ])
      // Journal "page".
      if (inRoundedRect(x, y, 64 * s, 52 * s, size - 64 * s, size - 52 * s, 16 * s)) {
        setPx(canvas, x, y, [240, 243, 250, 255])
        // Ruled lines on the page.
        const lineIdx = Math.floor((y - 84 * s) / (34 * s))
        const onLine =
          y > 84 * s &&
          y < size - 72 * s &&
          (y - 84 * s) % (34 * s) < 8 * s &&
          x > 84 * s &&
          x < size - 84 * s &&
          lineIdx >= 0
        if (onLine) {
          // First line is the accent "today" line.
          const accent = lineIdx === 0 ? [124, 156, 245, 255] : [178, 188, 210, 255]
          setPx(canvas, x, y, accent)
        }
      }
    }
  }
  return encodePng(size, size, canvas.data)
}

mkdirSync('resources', { recursive: true })
writeFileSync('resources/icon.png', drawIcon(256))

const trayPng = drawIcon(16)
writeFileSync(
  'src/main/trayIcon.ts',
  `// Generated by scripts/gen-icons.mjs — do not edit by hand.\nexport const TRAY_ICON_DATA_URL =\n  'data:image/png;base64,${trayPng.toString('base64')}'\n`
)

console.log('Wrote resources/icon.png and src/main/trayIcon.ts')
